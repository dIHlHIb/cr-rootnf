"""Generate search_tables.h: double-double constants for the hard-case search."""
import gmpy2
from gmpy2 import mpfr
gmpy2.get_context().precision = 300
def dd(v):
    hi = float(v); lo = float(v - mpfr(hi)); return hi, lo
h = lambda v: float(v).hex()
L = ["// Generated by gen_search_tables.py - do not edit.", "#pragma once"]
L.append("static const double LN2_DD[2] = {%s,%s};" % tuple(h(v) for v in dd(gmpy2.log(2))))
L.append("static const double INVFACT_DD[12][2] = {" + ",".join(
    "{%s,%s}" % tuple(h(v) for v in dd(mpfr(1) / gmpy2.fac(j))) for j in range(12)) + "};")
open("search_tables.h", "w").write("\n".join(L) + "\n")
print("ok")
