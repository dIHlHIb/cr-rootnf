"""Generate the complete map of nontrivial odd powers that fit in 24 bits."""
from pathlib import Path

size = 512
keys = [0]*size
roots = [0]*size
for n in range(3, 16):
    r = 3
    while r**n < 1 << 24:
        odd = r**n
        key = (n << 24) | odd
        i = ((key * 2654435761) & 0xffffffff) >> 23
        while keys[i]:
            i = (i + 1) % size
        keys[i], roots[i] = key, r
        r += 2
path = Path(__file__).resolve().parents[1] / "src/binary32/rootn/exact_table.h"
with path.open("w") as f:
    f.write('/* SPDX-License-Identifier: MIT\n   Copyright (c) 2026 dIHlHIb\n   Developed with AI assistance. */\n')
    f.write("/* Generated by tests/gen_exact.py. */\n")
    for typ,name,values in (("uint32_t","root_keys",keys),("uint8_t","root_odds",roots)):
        f.write(f"static const {typ} {name}[512] = {{\n")
        for i in range(0,size,12):
            f.write("  "+", ".join(hex(v) for v in values[i:i+12])+",\n")
        f.write("};\n")
