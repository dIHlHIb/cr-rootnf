"""Generate rootnf_tables.h: log2 / exp2 tables and polynomial coefficients.

All constants are computed with MPFR at 300 bits and split into double-double.
"""
import gmpy2
from gmpy2 import mpfr

gmpy2.get_context().precision = 300


def dd(v):
    hi = float(v)
    lo = float(v - mpfr(hi))
    return hi, lo


def h(v):
    return float(v).hex()


lines = ['/* SPDX-License-Identifier: MIT\n   Copyright (c) 2026 dIHlHIb\n   Developed with AI assistance. */', "// Generated by gen_tables.py - do not edit.", "#pragma once", ""]

# log2 table: inv_i ~ 1/(1 + (i + 0.5)/128) rounded to 20 bits; T_i = -log2(inv_i)
inv, T = [], []
for i in range(128):
    c = mpfr(1) / (1 + (mpfr(i) + mpfr("0.5")) / 128)
    q = gmpy2.rint(c * 2**20) / 2**20  # 20-bit inverse so m*inv is exact in double
    inv.append(float(q))
    T.append(dd(-gmpy2.log2(q)))
lines.append("static const double LOG_INV[128] = {" + ",".join(h(v) for v in inv) + "};")
lines.append("static const double LOG_T[128][2] = {" +
             ",".join("{%s,%s}" % (h(a), h(b)) for a, b in T) + "};")

# exp2 table: E_j = 2^(j/64)
E = [dd(gmpy2.exp2(mpfr(j) / 64)) for j in range(64)]
lines.append("static const double EXP_T[64][2] = {" +
             ",".join("{%s,%s}" % (h(a), h(b)) for a, b in E) + "};")

ln2 = gmpy2.log(2)
# fast log2(1+r) = r * sum_{k=0..5} P[k] r^k, P[k] = (-1)^k / ((k+1) ln2)
P = [((-1) ** k) / ((k + 1) * ln2) for k in range(6)]
lines.append("static const double LOGP[6] = {" + ",".join(h(v) for v in P) + "};")
# fast 2^f - 1 = sum_{k=1..5} Q[k] f^k, Q[k] = ln2^k / k!
Q = [ln2 ** k / gmpy2.fac(k) for k in range(1, 6)]
lines.append("static const double EXPQ[5] = {" + ",".join(h(v) for v in Q) + "};")
# accurate log(1+r) series coefficients (-1)^(k+1)/k as double-double, k = 1..16
C = [dd(mpfr((-1) ** (k + 1)) / k) for k in range(1, 17)]
lines.append("static const double LOGC_DD[16][2] = {" +
             ",".join("{%s,%s}" % (h(a), h(b)) for a, b in C) + "};")
lines.append("static const double INVLN2_DD[2] = {%s,%s};" % tuple(h(v) for v in dd(1 / ln2)))
open("rootnf_tables.h", "w").write("\n".join(lines) + "\n")
print("ok")
